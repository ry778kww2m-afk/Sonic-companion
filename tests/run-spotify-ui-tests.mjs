import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const fn=html.match(/function spotifyPermissionNoticeText\(reason,language\)\{[\s\S]*?\n\}/);
assert.ok(fn,'pure permission message mapper exists');
const ctx={};vm.runInNewContext(fn[0]+';this.notice=spotifyPermissionNoticeText;',ctx);
const notice=ctx.notice;
assert.equal(notice(null,'en'),'','no permission issue produces no warning');
assert.equal(notice('unknown','en'),'','unknown state produces no warning');
assert.match(notice('status','en'),/user-read-playback-state/);
assert.match(notice('status','pt'),/user-read-currently-playing/);
assert.match(notice('control','en'),/Premium eligibility/);
assert.match(notice('control','pt'),/dispositivo ativo/);
assert.ok(!/After installing the latest build, tap Disconnect/i.test(html),'obsolete unconditional reconnect instruction removed');
assert.ok(/id="scopeNote"[^>]*class="callout hidden"|class="callout hidden"[^>]*id="scopeNote"/.test(html),'permission warning is initially hidden');
assert.ok(html.includes("if(res.status===403){setSpotifyPermissionIssue('status');"),'status denial activates warning on HTTP 403');
assert.ok(html.includes("if(res.status===403){setSpotifyPermissionIssue('control');"),'control denial activates warning on HTTP 403');
assert.ok(html.includes("const data=await res.json();setSpotifyPermissionIssue(null);setMessage("),'successful playback-state response clears permission warning');
assert.ok(html.includes("setMessage(lang==='pt'?'Conexão Spotify verificada."),'successful polling replaces temporary startup state');
console.log('PASS: permission guidance is hidden by default, reason-specific on 403, localized, and cleared on successful/empty playback status; startup connection message has resolved outcomes.');
